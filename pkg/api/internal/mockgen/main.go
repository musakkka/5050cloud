// Command mockgen writes web/src/api/mocks/handlers.gen.ts: one MSW handler
// per route in api.Routes, answering with a deterministic fixture built from
// the route's response type. Every JSON fixture is checked by the TypeScript
// compiler with `satisfies` against web/src/api/types.gen.ts, so a fixture
// can never drift from the contract. Run through `make gen-ts`.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"reflect"
	"regexp"
	"sort"
	"strings"

	"github.com/musakkka/5050cloud/pkg/api"
)

func main() {
	out := flag.String("out", "web/src/api/mocks/handlers.gen.ts", "output file")
	flag.Parse()
	src, err := generate()
	if err != nil {
		fmt.Fprintf(os.Stderr, "mockgen: %v\n", err)
		os.Exit(1)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "mockgen: cannot write %s: %v\n", *out, err)
		os.Exit(1)
	}
}

var wildcard = regexp.MustCompile(`\{([a-z]+)\}`)

func generate() ([]byte, error) {
	var b bytes.Buffer
	b.WriteString(`// SPDX-License-Identifier: AGPL-3.0-only
// Code generated by pkg/api/internal/mockgen from pkg/api.Routes. DO NOT EDIT.
// Run ` + "`make gen-ts`" + ` after changing pkg/api.

import { http, HttpResponse, ws, type RequestHandler, type WebSocketHandler } from "msw";
import type * as T from "../types.gen";

/** Every route of docs/SPEC.md section 11, in table order. */
export const routes: { method: string; path: string; stream: string }[] = [
`)
	for _, r := range api.Routes {
		fmt.Fprintf(&b, "  { method: %q, path: %q, stream: %q },\n", r.Method, fullPath(r), r.Stream)
	}
	b.WriteString("];\n\n")

	b.WriteString("/** HTTP handlers, one per non-WebSocket route. */\nexport const handlers: RequestHandler[] = [\n")
	var wsRoutes []api.Route
	for _, r := range api.Routes {
		if r.Stream == "ws" {
			wsRoutes = append(wsRoutes, r)
			continue
		}
		body, err := responseExpr(r)
		if err != nil {
			return nil, fmt.Errorf("%s %s: %w", r.Method, r.Path, err)
		}
		fmt.Fprintf(&b, "  http.%s(%q, () => %s),\n", strings.ToLower(r.Method), "*"+mswPath(r), body)
	}
	b.WriteString("];\n\n")

	b.WriteString("/** WebSocket links for the shell and tunnel routes; they echo what they receive. */\nexport const wsHandlers: WebSocketHandler[] = [\n")
	for _, r := range wsRoutes {
		fmt.Fprintf(&b, "  ws.link(%q).addEventListener(\"connection\", ({ client }) => {\n", "*"+mswPath(r))
		b.WriteString("    client.addEventListener(\"message\", (event) => client.send(event.data));\n  }),\n")
	}
	b.WriteString("];\n")
	return b.Bytes(), nil
}

func fullPath(r api.Route) string {
	if r.NoPrefix {
		return r.Path
	}
	return "/api/v1" + r.Path
}

func mswPath(r api.Route) string { return wildcard.ReplaceAllString(fullPath(r), ":$1") }

func responseExpr(r api.Route) (string, error) {
	switch r.Stream {
	case "redirect":
		return `new HttpResponse(null, { status: 302, headers: { Location: "/settings/github" } })`, nil
	case "sse":
		v := example(reflect.TypeOf(r.Resp), "", 0)
		j, err := json.Marshal(v)
		if err != nil {
			return "", err
		}
		return fmt.Sprintf("new HttpResponse(%q, { headers: { \"content-type\": \"text/event-stream\" } })",
			"event: message\ndata: "+string(j)+"\n\n"), nil
	}
	switch v := r.Resp.(type) {
	case nil:
		return "new HttpResponse(null, { status: 204 })", nil
	case api.Text:
		return fmt.Sprintf("new HttpResponse(%q, { headers: { \"content-type\": %q } })", textFixture(string(v)), string(v)), nil
	}
	t := reflect.TypeOf(r.Resp)
	j, err := json.MarshalIndent(example(t, "", 0), "  ", "  ")
	if err != nil {
		return "", err
	}
	return fmt.Sprintf("HttpResponse.json(%s satisfies %s)", j, tsType(t)), nil
}

func textFixture(contentType string) string {
	switch contentType {
	case "application/yaml":
		return "project: sturdy-otter\nservices: {}\n"
	case "image/svg+xml":
		return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16"><circle cx="8" cy="8" r="7"/></svg>`
	case "application/gzip":
		return ""
	}
	return "ok"
}

// tsType names the generated TypeScript type for a Go response type.
func tsType(t reflect.Type) string {
	switch t.Kind() {
	case reflect.Slice:
		return tsType(t.Elem()) + "[]"
	case reflect.String:
		if t.PkgPath() == "" {
			return "string"
		}
	}
	name := t.Name()
	if i := strings.Index(name, "["); i >= 0 { // generic: Page[github.com/.../api.Notification]
		arg := name[i+1 : len(name)-1]
		arg = arg[strings.LastIndex(arg, ".")+1:]
		return "T." + name[:i] + "<T." + arg + ">"
	}
	return "T." + name
}

// Fixed values keep the output deterministic.
const exampleTime = 1767225600000 // 2026-01-01T00:00:00Z

var enumExamples = map[reflect.Type]any{
	reflect.TypeOf(api.Status("")):           string(api.StatusOnline),
	reflect.TypeOf(api.Role("")):             string(api.RoleOwner),
	reflect.TypeOf(api.ProjectRole("")):      string(api.ProjectEditor),
	reflect.TypeOf(api.DeploymentStatus("")): string(api.DepSuccess),
	reflect.TypeOf(api.ServiceKind("")):      string(api.KindWeb),
}

// stringExample picks a plausible value from the JSON field name.
func stringExample(field string) string {
	f := strings.ToLower(field)
	switch {
	case f == "id" || strings.HasSuffix(f, "id"):
		return "id_01jexample0000000000000000"
	case strings.Contains(f, "email"):
		return "ada@example.com"
	case strings.Contains(f, "url") || f == "docs" || f == "link":
		return "https://console.example.com/"
	case strings.Contains(f, "domain") || f == "host":
		return "app-x7k2.203-0-113-7.sslip.io"
	case f == "ip" || strings.HasSuffix(f, "ip") || strings.HasSuffix(f, "ips"):
		return "203.0.113.7"
	case f == "name" || strings.HasSuffix(f, "name"):
		return "api"
	case f == "version" || strings.HasSuffix(f, "version"):
		return "v0.1.0"
	case f == "state" || f == "status":
		return "ok"
	case f == "error" || f == "message" || f == "text" || f == "diagnosis" || f == "reason":
		return "Example sentence."
	}
	return "example"
}

func example(t reflect.Type, field string, depth int) any {
	if v, ok := enumExamples[t]; ok {
		return v
	}
	if depth > 8 {
		return nil
	}
	switch t.Kind() {
	case reflect.Pointer:
		return example(t.Elem(), field, depth)
	case reflect.String:
		return stringExample(field)
	case reflect.Bool:
		return true
	case reflect.Int, reflect.Int32, reflect.Int64, reflect.Uint32, reflect.Uint64:
		f := strings.ToLower(field)
		if strings.HasSuffix(f, "at") || f == "ts" || f == "time" || f == "lastseen" || f == "lastused" || f == "from" || f == "until" || f == "pointintime" || f == "recoverableto" || f == "lastok" || f == "lastfired" {
			return exampleTime
		}
		return 1
	case reflect.Float32, reflect.Float64:
		return 0.5
	case reflect.Slice:
		if t.Elem().Kind() == reflect.Uint8 {
			return ""
		}
		return []any{example(t.Elem(), field, depth+1)}
	case reflect.Array:
		out := make([]any, t.Len())
		for i := range out {
			out[i] = example(t.Elem(), field, depth+1)
		}
		return out
	case reflect.Map:
		return map[string]any{"example": example(t.Elem(), field, depth+1)}
	case reflect.Interface:
		return nil
	case reflect.Struct:
		obj := map[string]any{}
		addFields(t, obj, depth)
		return orderedMap(obj)
	}
	return nil
}

func addFields(t reflect.Type, obj map[string]any, depth int) {
	for i := 0; i < t.NumField(); i++ {
		f := t.Field(i)
		if !f.IsExported() {
			continue
		}
		name, _, _ := strings.Cut(f.Tag.Get("json"), ",")
		if name == "-" {
			continue
		}
		if f.Anonymous && name == "" {
			addFields(f.Type, obj, depth)
			continue
		}
		if f.Type.Kind() == reflect.Interface {
			if !strings.Contains(f.Tag.Get("json"), "omitempty") {
				obj[name] = nil // required "unknown" field, e.g. DiffEntry.old
			}
			continue
		}
		obj[name] = example(f.Type, name, depth+1)
	}
}

// orderedMap is a map that marshals with sorted keys (encoding/json already
// sorts map keys; this keeps the intent explicit).
type orderedMap map[string]any

func (m orderedMap) MarshalJSON() ([]byte, error) {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	var b bytes.Buffer
	b.WriteByte('{')
	for i, k := range keys {
		if i > 0 {
			b.WriteByte(',')
		}
		kj, _ := json.Marshal(k)
		vj, err := json.Marshal(m[k])
		if err != nil {
			return nil, err
		}
		b.Write(kj)
		b.WriteByte(':')
		b.Write(vj)
	}
	b.WriteByte('}')
	return b.Bytes(), nil
}
