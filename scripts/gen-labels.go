//go:build ignore

// gen-labels writes two frozen files from docs/SPEC.md:
//
//   - web/e2e/labels.json: every Railway label of section 2 (the "Railway
//     label" column) and the deployment labels of 9.1.1. labels.spec.ts
//     (WP8a) checks the rendered console against it.
//   - e2e/v1-checklist.json: one row per section 2 feature and per DX item
//     of section 23.1, for the V1 verifier to mark matched, better or missing.
//
// For each label it records which source tags reference/research/railway-ui.md
// gives on lines that mention it ([D] docs, [C] changelog, [W] web, [O]
// observed). A label backed only by [O] (or by nothing) has needsLiveCheck
// set; SPEC 19.0 item 4 records the result of the live check.
//
// Run: go run scripts/gen-labels.go (make labels).
package main

import (
	"bufio"
	"encoding/json"
	"fmt"
	"os"
	"regexp"
	"sort"
	"strings"
)

type label struct {
	Text string   `json:"text"`
	Tags []string `json:"tags"`
	// InDocs is true when the label appears verbatim in Railway's current
	// docs corpus (RAILWAY_DOCS, https://docs.railway.com/llms-full.txt).
	InDocs         bool `json:"inDocs"`
	NeedsLiveCheck bool `json:"needsLiveCheck"`
}

type row struct {
	ID      string  `json:"id"`
	Feature string  `json:"feature"`
	UI      bool    `json:"ui"` // false for CLI verbs, variable names and file names
	Labels  []label `json:"labels"`
}

type labelsFile struct {
	Source  string `json:"source"`
	Note    string `json:"note"`
	Rows    []row  `json:"rows"`
	Status  []row  `json:"statusLabels"`
	Version int    `json:"version"`
}

type checkItem struct {
	ID       string   `json:"id"`
	Source   string   `json:"source"`
	Item     string   `json:"item"`
	Ours     string   `json:"ours,omitempty"`
	Decision string   `json:"decision,omitempty"`
	Result   string   `json:"result"`   // "pending" | "matched" | "better" | "missing"
	Evidence []string `json:"evidence"` // U/E ids, screenshots
}

var tick = regexp.MustCompile("`([^`]+)`")

// docsCorpus is Railway's docs as one text file, when RAILWAY_DOCS is set.
var docsCorpus string
var tagRe = regexp.MustCompile(`\[(D|C|W|O)\b`)

// nonUI rows hold names that are not console strings.
var nonUI = map[string]bool{"D15": true, "D17": true, "D19": true, "D36": true}

func main() {
	spec, err := os.ReadFile("docs/SPEC.md")
	if err != nil {
		fail("cannot read docs/SPEC.md: %v (run from the repository root)", err)
	}
	research, _ := os.ReadFile("reference/research/railway-ui.md")
	if len(research) == 0 {
		research, _ = os.ReadFile("reference/research/railway-ui.md")
	}
	researchLines := strings.Split(string(research), "\n")
	if p := os.Getenv("RAILWAY_DOCS"); p != "" {
		b, err := os.ReadFile(p)
		if err != nil {
			fail("cannot read RAILWAY_DOCS=%s: %v", p, err)
		}
		docsCorpus = string(b)
	}

	sec2 := section(string(spec), "## 2.", "## 3.")
	var rows []row
	var checklist []checkItem
	for _, cols := range tableRows(sec2) {
		if len(cols) < 5 || !strings.HasPrefix(cols[0], "D") {
			continue
		}
		r := row{ID: cols[0], Feature: cols[1], UI: !nonUI[cols[0]], Labels: []label{}}
		for _, m := range tick.FindAllStringSubmatch(cols[2], -1) {
			r.Labels = append(r.Labels, newLabel(m[1], researchLines))
		}
		rows = append(rows, r)
		checklist = append(checklist, checkItem{ID: "V1-" + cols[0], Source: "SPEC 2", Item: cols[1], Ours: cols[3], Result: "pending", Evidence: []string{}})
	}
	if len(rows) != 40 {
		fail("expected 40 rows D1..D40 in section 2, found %d; the table layout changed", len(rows))
	}

	sec911 := section(string(spec), "#### 9.1.1", "### 9.2")
	statusRow := row{ID: "9.1.1", Feature: "Deployment status labels", UI: true}
	seen := map[string]bool{}
	for _, cols := range tableRows(sec911) {
		if len(cols) < 2 {
			continue
		}
		for _, m := range tick.FindAllStringSubmatch(cols[1], -1) {
			if !seen[m[1]] {
				seen[m[1]] = true
				statusRow.Labels = append(statusRow.Labels, newLabel(m[1], researchLines))
			}
		}
	}
	if len(statusRow.Labels) < 10 {
		fail("found only %d status labels in 9.1.1", len(statusRow.Labels))
	}

	sec231 := section(string(spec), "### 23.1", "### 23.2")
	n := 0
	for _, cols := range tableRows(sec231) {
		if len(cols) < 2 || cols[0] == "Item" {
			continue
		}
		n++
		checklist = append(checklist, checkItem{ID: fmt.Sprintf("V1-X%02d", n), Source: "SPEC 23.1", Item: cols[0], Decision: cols[1], Result: "pending", Evidence: []string{}})
	}

	write("web/e2e/labels.json", labelsFile{
		Version: 1,
		Source:  "docs/SPEC.md section 2 (Railway label column) and 9.1.1, generated by scripts/gen-labels.go",
		Note:    "Frozen by M0 on 2026-10-22. tags are the railway-ui.md source tags on lines that mention the label; inDocs means the label appears verbatim in Railway's docs of that day; needsLiveCheck marks labels backed by neither. See docs/SPEC.md 19.0 item 4.",
		Rows:    rows,
		Status:  []row{statusRow},
	})
	write("e2e/v1-checklist.json", map[string]any{
		"version": 1,
		"source":  "docs/SPEC.md section 2 and 23.1, generated by scripts/gen-labels.go",
		"items":   checklist,
	})
}

func newLabel(text string, research []string) label {
	tags := map[string]bool{}
	for _, l := range research {
		if strings.Contains(l, text) {
			for _, m := range tagRe.FindAllStringSubmatch(l, -1) {
				tags[m[1]] = true
			}
		}
	}
	l := label{Text: text, Tags: []string{}, InDocs: docsCorpus != "" && strings.Contains(docsCorpus, text)}
	for t := range tags {
		l.Tags = append(l.Tags, t)
	}
	sort.Strings(l.Tags)
	l.NeedsLiveCheck = !(l.InDocs || tags["D"] || tags["C"] || tags["W"])
	return l
}

func section(s, start, end string) string {
	i := strings.Index(s, "\n"+start)
	if i < 0 {
		fail("section %q not found in docs/SPEC.md", start)
	}
	s = s[i+1:]
	if j := strings.Index(s, "\n"+end); j >= 0 {
		s = s[:j]
	}
	return s
}

func tableRows(s string) [][]string {
	var out [][]string
	sc := bufio.NewScanner(strings.NewReader(s))
	sc.Buffer(make([]byte, 1<<20), 1<<20)
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if !strings.HasPrefix(line, "|") || strings.HasPrefix(line, "|---") {
			continue
		}
		line = strings.ReplaceAll(line, `\|`, "\x00")
		parts := strings.Split(strings.Trim(line, "|"), "|")
		for i := range parts {
			parts[i] = strings.TrimSpace(strings.ReplaceAll(parts[i], "\x00", "|"))
		}
		out = append(out, parts)
	}
	return out
}

func write(path string, v any) {
	b, err := json.MarshalIndent(v, "", "  ")
	if err != nil {
		fail("encode %s: %v", path, err)
	}
	if err := os.MkdirAll(dir(path), 0o755); err != nil {
		fail("create %s: %v", dir(path), err)
	}
	if err := os.WriteFile(path, append(b, '\n'), 0o644); err != nil {
		fail("write %s: %v", path, err)
	}
	fmt.Println("wrote", path)
}

func dir(p string) string {
	if i := strings.LastIndex(p, "/"); i >= 0 {
		return p[:i]
	}
	return "."
}

func fail(format string, a ...any) {
	fmt.Fprintf(os.Stderr, "gen-labels: "+format+"\n", a...)
	os.Exit(1)
}
