func TestExecIPTablesErrors(t *testing.T) {
	e := &execIPTables{save: "5050-no-such-iptables-save", store: "5050-no-such-iptables-restore"}
	if _, err := e.Save(context.Background()); err == nil || !strings.Contains(err.Error(), "not installed") {
		t.Errorf("save err = %v", err)
	}
	if err := e.Restore(context.Background(), ""); err == nil || !strings.Contains(err.Error(), "not installed") {
		t.Errorf("restore err = %v", err)
	}
	e = &execIPTables{save: "false", store: "false"}
	if _, err := e.Save(context.Background()); err == nil {
		t.Error("failing save not reported")
	}
	if err := e.Restore(context.Background(), ""); err == nil || !strings.Contains(err.Error(), "previous rules are still in place") {
		t.Errorf("restore err = %v", err)
	}
	if got := firstLine("iptables-restore: line 4 failed\nmore\nError occurred at line: 4", errors.New("x")); !strings.Contains(got, "line: 4") {
		t.Errorf("firstLine = %q", got)
	}
	if got := firstLine("", errors.New("exit status 1")); got != "exit status 1" {
		t.Errorf("firstLine = %q", got)
	}
}
