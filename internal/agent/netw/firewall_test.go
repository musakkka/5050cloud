func TestFirewallRulesCoverSpec(t *testing.T) {
	out := renderRestore(renderRules(testSpec(t)), savedState{})
	for _, want := range []string{
		// metadata and mesh blocked, with the opt-in replica first
		"-A 5050-ISOLATE -s 10.129.4.9/32 -d 169.254.169.254/32 -j RETURN",
		"-A 5050-ISOLATE -d 169.254.169.254/32 -j DROP",
		"-A 5050-ISOLATE -s 10.128.0.0/9 -d 100.96.0.0/16 -j DROP",
		// same environment across hosts, other environments dropped
		"-A 5050-ISOLATE -s 10.130.7.0/24 -j " + envChain("env_prod"),
		"-A " + envChain("env_prod") + " -d 10.130.7.0/24 -j ACCEPT",
		"-A 5050-ISOLATE -s 10.128.0.0/9 -d 10.128.0.0/9 -j DROP",
		// egress allowlist with a resolved hostname
		"-A " + egrChain("env_quarantine") + " -d 192.0.2.10/32 -j RETURN",
		"-A " + egrChain("env_quarantine") + " -j REJECT --reject-with icmp-admin-prohibited",
		// host access: only own gateway DNS and the build registry
		"-A 5050-HOSTIN -s 10.129.5.0/24 -d 10.129.5.1/32 -p udp -m udp --dport 53 -j ACCEPT",
		"-A 5050-HOSTIN -s 10.128.255.0/24 -d 10.128.255.1/32 -p tcp -m tcp --dport 5000 -j ACCEPT",
		"-A 5050-HOSTIN -j DROP",
		"-I INPUT 1 -s 10.128.0.0/9 -j 5050-HOSTIN",
		// MSS clamp and no masquerade between pods
		"-A 5050-MSS -o wg5050 -p tcp -m tcp --tcp-flags SYN,RST SYN -j TCPMSS --clamp-mss-to-pmtu",
		"-A 5050-NAT -s 10.128.0.0/9 -d 10.128.0.0/9 -j ACCEPT",
		// DOCKER-USER created before Docker starts
		":DOCKER-USER - [0:0]",
	} {
		if !strings.Contains(out, want+"\n") {
			t.Errorf("rendered rules lack %q", want)
		}
	}
	// The allowed environment has no egress chain.
	if strings.Contains(out, egrChain("env_prod")) {
		t.Error("an environment with egress allowed got an egress chain")
	}
}

func TestFirewallDirtyStateCleanup(t *testing.T) {
	out := renderRestore(renderRules(testSpec(t)), parseSave(savedDirty))
	for _, want := range []string{
		"-D INPUT -s 10.0.0.0/9 -j 5050-HOSTIN",
		"-D POSTROUTING -j 5050-NAT", // the duplicate
		"-F 5050-E-0000000000",
		"-X 5050-E-0000000000",
		"-I INPUT 1 -s 10.128.0.0/9 -j 5050-HOSTIN",
	} {
		if !strings.Contains(out, want+"\n") {
			t.Errorf("restore input lacks %q", want)
		}
	}
	if strings.Count(out, "-D POSTROUTING -j 5050-NAT") != 1 {
		t.Error("exactly one duplicate NAT hook should be removed")
	}
	if strings.Contains(out, ":DOCKER-USER") {
		t.Error("an existing DOCKER-USER chain must not be declared (that would flush Docker's rules)")
	}
	for _, unwanted := range []string{"-I DOCKER-USER", "-I POSTROUTING", "-I FORWARD"} {
		if strings.Contains(out, unwanted) {
			t.Errorf("hook already present but inserted again: %s", unwanted)
		}
	}
}

func TestFirewallSpecErrors(t *testing.T) {
	plan, _ := NewAddressPlan("", "")
	nets := []proto.Network{
		{EnvironmentID: "", Subnet: "10.129.1.0/24"},
		{EnvironmentID: "a", Subnet: "10.129.1.0/25"},
		{EnvironmentID: "b", Subnet: "192.168.1.0/24"},
		{EnvironmentID: "c", Subnet: "10.128.255.0/24"},
		{EnvironmentID: "d", Subnet: "bad"},
		{EnvironmentID: "e", Subnet: "10.129.2.0/24", Gateway: "10.9.9.9", PeerSubnets: []string{"x"}, AllowMetadata: []string{"10.1.1.1"},
			Egress: "blocked", EgressAllow: []string{"fd00::1", "nowhere.invalid", "", "fd00::/64"}},
		{EnvironmentID: "e", Subnet: "10.129.3.0/24"},
	}
	spec, errs := buildFirewallSpec(context.Background(), plan, nets, fakeResolve)
	if len(spec.Envs) != 1 || spec.Envs[0].ID != "e" {
		t.Fatalf("envs = %+v", spec.Envs)
	}
	e := spec.Envs[0]
	if e.Gateway.String() != "10.129.2.1" || len(e.Subnets) != 1 || len(e.AllowMetadata) != 0 || len(e.EgressAllow) != 0 {
		t.Errorf("bad entries leaked into the spec: %+v", e)
	}
	if len(errs) != 13 {
		for _, err := range errs {
			t.Log(err)
		}
		t.Errorf("got %d errors, want 13", len(errs))
	}
	for _, err := range errs {
		if s := err.Error(); s == "" || strings.Contains(s, "\u2014") {
			t.Errorf("bad error text %q", s)
		}
	}
	if _, err := parseAllowEntry(context.Background(), "host.example", nil); err == nil {
		t.Error("hostname without a resolver accepted")
	}
	none := func(context.Context, string) ([]netip.Addr, error) {
		return []netip.Addr{netip.MustParseAddr("2001:db8::1")}, nil
	}
	if _, err := parseAllowEntry(context.Background(), "v6.example", none); err == nil {
		t.Error("hostname with only IPv6 accepted")
	}
}

func TestParseSaveAndSync(t *testing.T) {
	rs := renderRules(testSpec(t))
	// What a host looks like right after our restore (Docker running).
	var b strings.Builder
	for _, tbl := range rs.tables {
		b.WriteString("*" + tbl.name + "\n")
		if tbl.name == "filter" {
			b.WriteString(":DOCKER-USER - [0:0]\n")
		}
		for _, c := range tbl.chains {
			b.WriteString(":" + c + " - [0:0]\n")
		}
		for _, h := range rs.hooks {
			if h.table == tbl.name {
				b.WriteString(h.line() + "\n")
			}
		}
		for _, c := range tbl.chains {
			for _, r := range tbl.rules[c] {
				b.WriteString("-A " + c + " " + r + "\n")
			}
		}
		b.WriteString("COMMIT\n")
	}
	st := parseSave(b.String())
	if !inSync(rs, st) {
		t.Fatal("freshly applied rules reported out of sync")
	}
	if inSync(rs, parseSave(savedDirty)) {
		t.Error("dirty rules reported in sync")
	}
	// A missing rule in one of our chains is noticed.
	st.rules["filter"][chainHostIn] = st.rules["filter"][chainHostIn][1:]
	if inSync(rs, st) {
		t.Error("a deleted rule went unnoticed")
	}
}

// fakeIPT records restores and keeps the saved text consistent with them,
// the way the kernel would.
type fakeIPT struct {
	mu       sync.Mutex
	saved    string
	restores []string
	failNext error
}

func (f *fakeIPT) Save(context.Context) (string, error) {
	f.mu.Lock()
	defer f.mu.Unlock()
	return f.saved, nil
}

func (f *fakeIPT) Restore(_ context.Context, in string) error {
	f.mu.Lock()
	defer f.mu.Unlock()
	if f.failNext != nil {
		err := f.failNext
		f.failNext = nil
		return err
	}
	f.restores = append(f.restores, in)
	f.saved = simulateRestore(f.saved, in)
	return nil
}

// simulateRestore applies the subset of restore commands we emit to saved text.
func simulateRestore(saved, in string) string {
	st := parseSave(saved)
	order := []string{}
	for tbl := range st.chains {
		order = append(order, tbl)
	}
	cur := ""
	for _, line := range strings.Split(in, "\n") {
		f := strings.Fields(line)
		if len(f) == 0 {
			continue
		}
		switch {
		case strings.HasPrefix(line, "*"):
			cur = line[1:]
			if st.chains[cur] == nil {
				st.chains[cur] = map[string]bool{}
				st.rules[cur] = map[string][]string{}
				order = append(order, cur)
			}
		case strings.HasPrefix(line, ":"):
			st.chains[cur][f[0][1:]] = true
		case f[0] == "-F":
			st.rules[cur][f[1]] = nil
		case f[0] == "-X":
			delete(st.chains[cur], f[1])
			delete(st.rules[cur], f[1])
		case f[0] == "-A":
			st.rules[cur][f[1]] = append(st.rules[cur][f[1]], line)
		case f[0] == "-I":
			spec := strings.Join(f[3:], " ")
			st.rules[cur][f[1]] = append([]string{"-A " + f[1] + " " + spec}, st.rules[cur][f[1]]...)
		case f[0] == "-D":
			want := "-A" + strings.TrimPrefix(line, "-D")
			rs := st.rules[cur][f[1]]
			for i, r := range rs {
				if r == want {
					st.rules[cur][f[1]] = append(rs[:i:i], rs[i+1:]...)
					break
				}
			}
		}
	}
	var b strings.Builder
	for _, tbl := range order {
		b.WriteString("*" + tbl + "\n")
		for c := range st.chains[tbl] {
			b.WriteString(":" + c + " - [0:0]\n")
		}
		for _, rs := range st.rules[tbl] {
			for _, r := range rs {
				b.WriteString(r + "\n")
			}
		}
		b.WriteString("COMMIT\n")
	}
	return b.String()
}

func TestNetApplyFirewallIdempotent(t *testing.T) {
	n, ipt, _, _ := newTestNet(t)
	ctx := context.Background()
	host := proto.HostConfig{}
	if err := n.Apply(ctx, host, proto.Mesh{}, testNets(), nil); err != nil {
		t.Fatal(err)
	}
	if err := n.Apply(ctx, host, proto.Mesh{}, testNets(), nil); err != nil {
		t.Fatal(err)
	}
	if len(ipt.restores) != 1 {
		t.Fatalf("an unchanged state restored the rules %d times, want 1", len(ipt.restores))
	}
	// Someone flushes a chain by hand: the next apply repairs it.
	ipt.mu.Lock()
	ipt.saved = strings.ReplaceAll(ipt.saved, "-A 5050-HOSTIN -j DROP\n", "")
	ipt.mu.Unlock()
	if err := n.Apply(ctx, host, proto.Mesh{}, testNets(), nil); err != nil {
		t.Fatal(err)
	}
	if len(ipt.restores) != 2 {
		t.Fatalf("a damaged rule set was not repaired (%d restores)", len(ipt.restores))
	}
	// A failing restore is reported as a sentence and retried next time.
	ipt.failNext = errors.New("iptables-restore: line 3 failed")
	nets := testNets()
	nets[1].Egress = "allowed"
	if err := n.Apply(ctx, host, proto.Mesh{}, nets, nil); err == nil {
		t.Fatal("restore failure not reported")
	}
	if err := n.Apply(ctx, host, proto.Mesh{}, nets, nil); err != nil {
		t.Fatal(err)
	}
	if len(ipt.restores) != 3 {
		t.Fatalf("restores = %d, want 3", len(ipt.restores))
	}
}

